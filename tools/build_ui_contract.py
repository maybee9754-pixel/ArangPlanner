#!/usr/bin/env python3
"""Generate WoW Lua geometry and matching browser CSS from docs/design.json.
This is the only authoritative set of interactive layout measurements.
"""
from pathlib import Path
import json,sys

root=Path(__file__).resolve().parent.parent
spec=json.loads((root/"docs/design.json").read_text(encoding="utf-8"))
addon=root/"ArangPlanner"
website=root/"docs"
addon.mkdir(exist_ok=True)
website.mkdir(exist_ok=True)

def lua_table(value):
    if isinstance(value,dict):
        return "{"+",".join("["+json.dumps(str(k),ensure_ascii=False)+"]="+lua_table(v) for k,v in value.items())+"}"
    if isinstance(value,list):
        return "{"+",".join(lua_table(x) for x in value)+"}"
    if isinstance(value,bool):return "true" if value else "false"
    if isinstance(value,(int,float)):return str(value)
    if value is None:return "nil"
    return json.dumps(str(value),ensure_ascii=False)

fields=["gameVersion","designResolution","panels","tabs","close","controls","table","typography","typeface"]
payload={key:spec[key] for key in fields}
(addon/"UIContract.lua").write_text(
    "-- Generated from docs/design.json by tools/build_ui_contract.py.\n"
    "-- Do not hand-edit: this is the common web/game UI design contract.\n"
    "ArangPlannerUIContract = "+lua_table(payload)+"\n",encoding="utf-8")

css=[
"/* Generated by tools/build_ui_contract.py from docs/design.json. */",
"@font-face{font-family:'ArangNanum';src:url('assets/fonts/NanumGothic-Regular.ttf') format('truetype');font-style:normal;font-weight:400;font-display:swap}",
"@font-face{font-family:'ArangNanum';src:url('assets/fonts/NanumGothic-Bold.ttf') format('truetype');font-style:normal;font-weight:700;font-display:swap}",
"@font-face{font-family:'ArangNanum';src:url('assets/fonts/NanumGothic-ExtraBold.ttf') format('truetype');font-style:normal;font-weight:800 900;font-display:swap}",
":root,body,button,input{font-family:'ArangNanum',sans-serif !important}",
":root{font-size:%dpx !important}"%spec["typography"]["small"],
".canvas{width:%dpx !important;height:%dpx !important}"%(spec["designResolution"]["width"],spec["designResolution"]["height"]),
]
mapping={"header":".head","left":".panel.left","middle":".panel.center","right":".panel.right"}
for name,selector in mapping.items():
    p=spec["panels"][name]
    css.append(f"{selector}{{left:{p['x']}px !important;top:{p['y']}px !important;width:{p['w']}px !important;height:{p['h']}px !important}}")
css.extend([".head .nav{position:absolute !important;left:0;top:0;width:100%;height:100%;display:block !important;pointer-events:none}",
".head .nav .tab{position:absolute !important;min-width:0 !important;pointer-events:auto;border-radius:0 !important;padding:0 !important;font-size:13px !important}"])
for i,p in enumerate(spec["tabs"]):
    css.append(".head .nav .tab:nth-child(%d){left:%dpx !important;top:%dpx !important;width:%dpx !important;height:%dpx !important}"%(i+1,p["x"],p["y"],p["w"],p["h"]))
p=spec["close"]
css.append(".head .close{position:absolute !important;margin:0 !important;left:%dpx !important;top:%dpx !important;width:%dpx !important;height:%dpx !important}"%(p["x"],p["y"],p["w"],p["h"]))
css.extend([
".center .body{padding:0 !important}",
".center .specrow{position:absolute !important;left:14px;top:47px;margin:0}",
".center .controls{position:absolute !important;left:0;top:0;display:block !important;margin:0;width:100%;height:100%;pointer-events:none}",
".center .controls>*{position:absolute !important;pointer-events:auto}",
".center .hint{position:absolute !important;left:16px;top:115px;margin:0}",
".center #table{position:absolute !important;inset:0;pointer-events:none}",
".center #table>*{pointer-events:auto}",
])
sel=["#itemInput","#add","#remove","#reset"]
for key,selector in zip(["input","add","remove","refresh"],sel):
    p=spec["controls"][key]
    css.append(".center "+selector+"{left:%dpx !important;top:%dpx !important;width:%dpx !important;height:%dpx !important;margin:0 !important}"%(p["x"],p["y"],p["w"],p["h"]))
p=spec["table"]["header"]
css.append(".center .tablehead{position:absolute !important;left:%dpx;top:%dpx;width:%dpx;height:%dpx;margin:0;display:grid;grid-template-columns:435px 101px 1fr;padding:0 0 0 39px}"%(p["x"],p["y"],p["w"],p["h"]))
p=spec["table"]["rows"]
css.append(".center #rows{position:absolute !important;left:%dpx;top:%dpx;width:%dpx}"%(p["x"],p["y"],p["w"]))
css.append(".center .tableline{height:%dpx !important;margin:0 0 %dpx !important;padding-left:5px;grid-template-columns:467px 103px 1fr}"%(p["h"],p["gap"]))
css.append(".center .tableline .name{gap:8px}")
css.append(".item-icon{width:%dpx !important;height:%dpx !important}"%(spec["table"]["iconSize"],spec["table"]["iconSize"]))
css.append(".game-help>div{height:%dpx !important;line-height:%dpx !important}"%(spec["typography"]["rightHelpLineHeight"],spec["typography"]["rightHelpLineHeight"]))
css.append(".identity b{font-size:%dpx !important}.spec,.specrow{font-size:%dpx !important}.eyebrow,.muted,.hint,.game-help,.tableline{font-size:%dpx !important}"%(spec["typography"]["large"],spec["typography"]["normal"],spec["typography"]["small"]))
# All browser inner text anchors mirror the WoW FontString TOPLEFT / LEFT points.
# A grid auto-width cannot reproduce the exact x pixel of game table columns.
cal=spec["previewCalibration"]
left=cal["left"]
right=cal["right"]
mid=cal["middle"]
head=cal["header"]
foot=cal["footer"]
css.extend([
".canvas{border:1px solid #494252;overflow:hidden}",
".panel.left .body,.panel.right .body{padding:0 !important}",
".panel.left .eyebrow,.panel.left .spec,.panel.left .stat,.panel.left .rule,.panel.left .missing,.panel.left #missingList{position:absolute !important;margin:0 !important}",
".panel.left .eyebrow{left:14px;top:%dpx;line-height:15px}"%left["summaryY"],
".panel.left .spec{left:14px;top:%dpx;line-height:17px}"%left["specY"],
".panel.left .stat{left:14px;top:%dpx;line-height:17px}"%left["progressY"],
".panel.left .stat .rose{position:absolute;left:0;top:%dpx;width:238px;white-space:nowrap;line-height:18px}"%(left["detailY"]-left["progressY"]),
".panel.left .rule{left:14px;top:%dpx;width:228px;height:1px}"%left["dividerY"],
".panel.left .missing{left:14px;top:%dpx;line-height:17px}"%left["missingTitleY"],
".panel.left #missingList{left:17px;top:%dpx;line-height:18px;max-width:221px}"%left["missingRowsY"],
".panel.right h4,.panel.right .muted,.panel.right .game-help{position:absolute !important;margin:0 !important;left:14px}",
".panel.right h4{top:%dpx;line-height:18px;white-space:nowrap}"%right["titleY"],
".panel.right .muted{top:%dpx;line-height:18px}"%right["noteY"],
".panel.right .game-help{top:%dpx;line-height:18px}"%right["helpY"],
".center .specrow{top:%dpx !important;line-height:18px}"%mid["specY"],
".center .hint{top:%dpx !important;line-height:17px}"%mid["hintY"],
".center .tablehead{display:block !important;gap:0 !important;padding:0 !important;border:0}",
".center .tablehead>span{position:absolute;top:0;line-height:%dpx;white-space:nowrap}"%spec["table"]["header"]["h"],
".center .tablehead>span:nth-child(1){left:%dpx}"%(spec["table"]["columns"]["name"]+2),
".center .tablehead>span:nth-child(2){left:%dpx}"%(spec["table"]["columns"]["id"]+2),
".center .tablehead>span:nth-child(3){left:%dpx}"%(spec["table"]["columns"]["status"]+2),
".center .tableline{position:relative !important;display:block !important;gap:0 !important;padding:0 !important}",
".center .tableline>span{position:absolute;top:0;line-height:%dpx;white-space:nowrap}"%spec["table"]["rows"]["h"],
".center .tableline .name{left:5px;display:flex;align-items:center;top:3px !important;line-height:24px !important;height:24px}",
".center .tableline .id{left:%dpx}"%spec["table"]["columns"]["id"],
".center .tableline .owned,.center .tableline .unknown{left:%dpx}"%spec["table"]["columns"]["status"],
".center .tableline .item-icon{border-radius:0;line-height:24px !important}",
".center .pagination{position:absolute;inset:0 !important;display:block !important;pointer-events:none}",
".center .pagination button{position:absolute;top:%dpx;height:%dpx;width:72px;pointer-events:auto;padding:0 !important}"%(mid["pageButtonsY"],mid["pageButtonsH"]),
".center #prev{left:%dpx}"%mid["pagePrevX"],
".center #next{left:%dpx}"%mid["pageNextX"],
".center #pages{position:absolute;bottom:%dpx;left:50%%;transform:translateX(-50%%);white-space:nowrap;line-height:15px}"%mid["pageLabelBottom"],
".canvas .footer-game{bottom:%dpx !important;line-height:13px;font-size:%dpx !important;white-space:nowrap}"%(foot["bottom"],foot["fontSize"]),
".head .identity{position:absolute;left:%dpx;top:0;height:100%%;display:flex;align-items:center;gap:%dpx;min-width:0}"%(head["markLeft"],head["brandGap"]),
".head .diamond{width:26px;height:26px;margin:0 4px 0 4px;border:0;background:#c7abe4;box-shadow:inset 0 0 0 5px #76508c}",
".head .identity b{margin-top:%dpx}"%head["brandOffsetY"],
".head .identity small{margin-left:%dpx;margin-top:1px}"%max(0,head["versionGap"]-head["brandGap"]),
".center #itemInput{padding:0 8px !important;border-radius:0 !important;font-weight:400 !important}",
".head .tab,.center .mini,.pagination .mini{border-radius:0 !important;box-shadow:none !important;text-shadow:none !important}",
])

# Correct only graphic backgrounds. In screenshots, web PNG composite appears
# around 4-5 RGB levels lighter than WoW TGA composite at the same coordinates.
# Applying CSS filter to parent would also darken Korean text; never do that.
cm=cal["colorMatch"]
css.extend([
".panel{background-image:linear-gradient(rgba(0,0,0,%.2f),rgba(0,0,0,%.2f)),url('assets/panel-body.png') !important;background-size:100%% 100%%,100%% 100%% !important}"%(cm["panelOverlayAlpha"],cm["panelOverlayAlpha"]),
".head{background-image:linear-gradient(rgba(0,0,0,%.2f),rgba(0,0,0,%.2f)),url('assets/header.png') !important;background-size:100%% 100%%,100%% 100%% !important}"%(cm["headerOverlayAlpha"],cm["headerOverlayAlpha"]),
".section,.center .tablehead{background-image:linear-gradient(rgba(0,0,0,%.2f),rgba(0,0,0,%.2f)),url('assets/panel-header.png') !important;background-size:100%% 100%%,100%% 100%% !important}"%(cm["sectionOverlayAlpha"],cm["sectionOverlayAlpha"]),
".center .tableline{background-image:linear-gradient(rgba(0,0,0,%.2f),rgba(0,0,0,%.2f)),url('assets/row.png') !important;background-size:100%% 100%%,100%% 100%% !important}"%(cm["rowOverlayAlpha"],cm["rowOverlayAlpha"]),
".head .tab:not(.active),.center .mini,.pagination .mini{background-image:linear-gradient(rgba(0,0,0,%.2f),rgba(0,0,0,%.2f)),url('assets/button-idle.png') !important;background-size:100%% 100%%,100%% 100%% !important}"%(cm["buttonOverlayAlpha"],cm["buttonOverlayAlpha"]),
".head .tab.active{background-image:url('assets/button-active.png') !important}",
".head .tab:hover,.center .mini:hover,.pagination .mini:hover{background-image:url('assets/button-hover.png') !important}",
])

# Web text must follow the corresponding WoW FontString style rather than
# inheriting browser semantic <strong>/<button> defaults.
css.extend([
".head .tab,.head .close,.center .mini,.pagination .mini{font-weight:400 !important}",
".section,.spec,.specrow,.tablehead,.missing,.identity b{font-weight:700 !important}",
".identity b{font-weight:800 !important}",
".stat,.stat strong,.stat .green,.stat .rose,.eyebrow,.muted,.hint,.right h4,.right .body,.game-help,.tableline,.pagination,.missingList{font-weight:400 !important}",
".right h4{font-size:13px !important}",
".center .tableline .name,.center .tableline .id,.center .tableline .owned,.center .tableline .unknown{font-weight:400 !important}",
".center .tablehead{font-weight:700 !important}",
".game-help{margin-top:25px !important}",
".panel.left .body{padding:14px !important}",
".panel.right .body{padding:14px !important}",
".canvas .footer-game{position:absolute;bottom:6px;left:0;width:100%;text-align:center;font-size:12px;font-weight:400;color:#9996ad;line-height:14px;pointer-events:none}",
".center .hint{font-weight:400 !important}",
".center .tableline .name .item-icon{font-size:14px !important}",
])
# R4: browser text baselines and section header geometry follow game FontStrings.
fm=cal["fontMatch"]
css.extend([
".section{position:relative !important;top:1px !important;margin:0 1px !important;width:calc(100% - 2px) !important;height:33px !important;padding:0 12px !important;display:flex !important;align-items:center !important;font-size:%dpx !important}"%fm["headingFontSize"],
".head .tab,.center .mini,.pagination .mini{line-height:normal !important;letter-spacing:0 !important}",
".panel.left .eyebrow,.panel.left .spec,.panel.left .stat,.panel.left .missing,.panel.right h4,.panel.right .muted,.center .specrow,.center .hint{letter-spacing:%s !important}"%fm["letterSpacing"],
".panel.left .stat{white-space:pre !important}",
".panel.left .stat .rose{white-space:pre !important}",
".canvas .footer-game{bottom:%dpx !important;line-height:14px !important;letter-spacing:0 !important;white-space:pre !important}"%foot["bottom"],
".right .game-help{font-weight:400 !important}",
".center .tableline .name,.center .tableline .id,.center .tableline .owned{letter-spacing:0 !important}",
])

(website/"ui-contract.css").write_text("\n".join(css)+"\n",encoding="utf-8")
print("Generated",addon/"UIContract.lua",website/"ui-contract.css")
